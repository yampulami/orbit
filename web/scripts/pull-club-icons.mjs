const names = [...new Set(GROUPS.flatMap(([, list]) => list))];
const res = await fetch(`https://api.iconify.design/${SET}.json?icons=${names.join(",")}`);
if (!res.ok) throw new Error(`Iconify answered ${res.status}`);
const data = await res.json();
const missing = new Set(data.not_found ?? []);
const have = (n) => data.icons?.[n];
const label = (n) => n.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());

let n = 0;
const rows = [];
const seen = new Set();
for (const [group, list] of GROUPS) {
  for (const name of list) {
    if (seen.has(name)) continue;
    seen.add(name);
    const id = n.toString(36).padStart(2, "0");
    n++;
    if (missing.has(name) || !have(name)) { console.warn("not in the set, skipped:", name); continue; }
    rows.push({ id, name, group, label: label(name), body: have(name).body });
  }
}

const out = `// Generated by scripts/pull-club-icons.mjs from Iconify. Do not edit by hand.
// Phosphor Icons (MIT licence): https://github.com/phosphor-icons/core  ·  fetched through https://iconify.design
export const CLUB_ICON_VIEWBOX = ${data.width ?? 256};
export type ClubIconRow = { id: string; name: string; group: string; label: string; body: string };
export const CLUB_ICON_GROUPS = ${JSON.stringify(GROUPS.map(([g]) => g))} as const;
export const CLUB_ICONS: ClubIconRow[] = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync(new URL("../src/lib/clubIcons.generated.ts", import.meta.url), out);
console.log(`wrote ${rows.length} icons (${missing.size} not found)`);
